"""Baseline B: 2-Agent system (Investigator + Analyst) without Verifier challenge."""

import logging
import time
from typing import List, Optional

from aletheia.evaluation.baselines.base import BaseDiagnosticSystem
from aletheia.evaluation.llm.client import BaseLLMClient
from aletheia.evaluation.models import DiagnosisResult
from aletheia.evidence.events import Timeline
from aletheia.evidence.schema import EvidenceItem

logger = logging.getLogger("aletheia.eval.baseline.two_agent")


class TwoAgentBaseline(BaseDiagnosticSystem):
    """Baseline B: 2-Agent system executing Investigator -> Analyst without Verifier scrutiny.

    Demonstrates failure modes of unverified multi-agent systems:
    - Anchoring to the first plausible hypothesis.
    - Failing to catch temporal order violations (e.g. causes postdating symptoms).
    - Accepting hypotheses contradicted by secondary telemetry.
    """

    def __init__(
        self,
        name: str = "Baseline-B-Two-Agent (Investigator+Analyst)",
        llm_client: Optional[BaseLLMClient] = None,
    ):
        super().__init__(name=name)
        from aletheia.agents.analyst import Analyst
        from aletheia.agents.investigator import Investigator
        self.investigator = Investigator(llm_client=llm_client)
        self.analyst = Analyst(llm_client=llm_client)

    def diagnose(
        self,
        incident_id: str,
        alert_description: str,
        evidence_items: List[EvidenceItem],
        timeline: Optional[Timeline] = None,
    ) -> DiagnosisResult:
        start_time = time.perf_counter()

        # Step 1: Investigator builds investigation context
        context = self.investigator.investigate(
            incident_id=incident_id,
            alert_description=alert_description,
            evidence_items=evidence_items,
            timeline=timeline,
        )

        # Step 2: Analyst generates hypotheses
        analyst_output = self.analyst.analyze(context)

        latency = round(time.perf_counter() - start_time, 4)

        if not analyst_output.hypotheses:
            return DiagnosisResult(
                incident_id=incident_id,
                root_cause="Analyst generated no candidate hypotheses",
                root_cause_category="unknown",
                suspected_component="unknown",
                introduced_by="unknown",
                affected_service="unknown",
                explanation="No hypotheses generated by the 2-agent system.",
                cited_evidence_ids=[],
                confidence=0.0,
                recommended_fix="Collect additional telemetry.",
                usage_metadata={"latency_seconds": latency},
            )

        # 2-Agent system blindly adopts the top-ranked hypothesis without Verifier audit
        top_hyp = analyst_output.hypotheses[0]

        # Extract service from entities
        affected_svc = "unknown"
        for ent in context.important_entities:
            if ent.type == "SERVICE":
                affected_svc = ent.name
                break

        return DiagnosisResult(
            incident_id=incident_id,
            root_cause=top_hyp.hypothesis,
            root_cause_category="slow_database_query" if "database" in top_hyp.hypothesis.lower() else "regression",
            suspected_component=top_hyp.suspected_component or "unknown",
            introduced_by=top_hyp.suspected_trigger or "unknown",
            affected_service=affected_svc,
            explanation=(
                f"Analyst top hypothesis {top_hyp.hypothesis_id}: {top_hyp.hypothesis} "
                f"(Unverified by Verifier; contradictions not challenged)."
            ),
            cited_evidence_ids=top_hyp.supporting_evidence_ids,
            confidence=top_hyp.confidence,
            recommended_fix="Inspect affected components and test resolution.",
            usage_metadata={
                "latency_seconds": latency,
                "agent_pipeline": ["Investigator", "Analyst"],
                "total_hypotheses_generated": len(analyst_output.hypotheses),
            },
        )
